let age=12;//This is number literal assigned to variable age
let name="jaasritha"//This is string literal assigned to variable name
let isStudent=true//This is boolean literal assigned to variable isStudent
let pi=3.14;//This is numeric literal assigned to variable pi
let nullValue=null//This is null literal assigned to variable nullValue
let undefinedValue;//The variable is declared but not assigned, so it has value 'undefined'

console.log(typeof age)//number
console.log(typeof name)//string
console.log(typeof undefinedValue)//undefined
console.log(typeof nullValue)//object
console.log(typeof isStudent)//boolean
console.log(typeof pi)//number