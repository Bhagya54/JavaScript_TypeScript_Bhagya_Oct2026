//preincrement
let a = 10;
let b = ++a;//(increment value of a)

//pre increment -> first increment the value of a and then assign the value of a
console.log(a)//11
console.log(b)//11


//predecrement
let a1 = 10;
let b1 = --a1;//(decrement value of a1) -9

//pre decrement -> first decrement the value of a1 and then assign the value of a1 to b1
console.log(a1)//9
console.log(b1)//9